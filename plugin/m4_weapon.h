#ifndef M4_WEAPON_H
#define M4_WEAPON_H
#include <string.h>

static const unsigned char M4_GUIDS[][16] = {{0x19, 0x35, 0x6b, 0x10, 0x07, 0x06, 0x29, 0x4b, 0xb7, 0xa2, 0x9d, 0x8f, 0xb5, 0x54, 0xa2, 0x3e}, {0xf2, 0x77, 0x36, 0x35, 0x74, 0x3b, 0x02, 0x4e, 0x94, 0xaa, 0xbe, 0x00, 0xe1, 0x58, 0x83, 0xb6}};

static inline int m4_is_weapon_record(const unsigned char *record) {
    for (size_t i = 0; record && i < sizeof(M4_GUIDS) / sizeof(M4_GUIDS[0]); i++)
        if (!memcmp(record + 8, M4_GUIDS[i], sizeof(M4_GUIDS[i]))) return 1;
    return 0;
}
#endif
