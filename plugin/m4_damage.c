static int m4_round(unsigned char *weapon, unsigned char *ammo) {
    unsigned char *record = ammo ? damage_record(ammo) : weapon ? damage_record(weapon) : NULL;
    if (!record) return 0;
    return ammo ? m4_is_ammo_record(record) : m4_is_weapon_record(record);
}

static int m4_hit(unsigned char *hit) {
    if (!m4_damage_fixed || !hit) return 0;
    unsigned char probe[HIT_WEAPON_ID + 8] = {0};
    memcpy(probe + HIT_WEAPON_ID, hit + HIT_AMMO_ID, 8);
    return m4_round(damage_item(hit), damage_item(probe));
}

static int damage_note_due(void) {
    return InterlockedIncrement(&damage_lines) <= DAMAGE_LINES;
}

static int channel_index(int channel) {
    return channel == 1 ? 0 : channel == 2 ? 1 : channel == 4 ? 2 : -1;
}

float m4_armour_factor(float range) {
    float start = (float)m4_armour_near, end = (float)m4_armour_far, rest = m4_armour_floor / 100.0f;
    rest = rest < 0.0f ? 0.0f : rest > 1.0f ? 1.0f : rest;
    if (range <= start) return 1.0f;
    if (end <= start || range >= end) return rest;
    return 1.0f - (1.0f - rest) * (range - start) / (end - start);
}

static float armour_factor(float defense, float range) {
    return defense > 0.0f ? m4_armour_factor(range) : 1.0f;
}

float m4_attack_value(float raw, float base, unsigned char *weapon, unsigned char *ammo, unsigned char *victim) {
    if (!m4_damage_fixed || !m4_round(weapon, ammo)) return raw;
    float fixed = m4_attack_hundredths > 0 ? m4_attack_hundredths / 100.0f : base;
    if (victim && damage_note_due()) {
        char line[96];
        snprintf(line, sizeof(line), "damage: M4 hit attack raw %.3f fixed %.3f", raw, fixed);
        note(line);
    }
    return fixed;
}

int m4_unaware_fixed(unsigned char *weapon, unsigned char *ammo, float attack) {
    if (!m4_damage_fixed || !m4_round(weapon, ammo)) return 0;
    if (damage_note_due()) {
        char line[96];
        snprintf(line, sizeof(line), "damage: M4 unaware bonus skipped, attack stays %.3f", attack);
        note(line);
    }
    return 1;
}

int m4_level_value(unsigned char *hit, void *victim) {
    if (!m4_hit(hit)) return damage_level(victim);
    if (damage_note_due()) note("damage: M4 hit skips the victim's combat level health reduction");
    return 0;
}

float m4_attack_scale(unsigned char *hit, void *buffs, float unused, float attack, unsigned char *args) {
    (void)unused;
    float scaled = damage_scale(NULL, buffs, ATTACK_STAT, attack, *(void **)args, args[8]);
    if (!m4_hit(hit)) return scaled;
    if (scaled != attack && damage_note_due()) {
        char line[112];
        snprintf(line, sizeof(line), "damage: M4 hit skips the attacker's damage buff, %.1f stays %.1f", scaled, attack);
        note(line);
    }
    return attack;
}

float m4_armour_attack(unsigned char *hit, int flag, float attack, float *lane, int channel) {
    float modified = damage_modify(hit, flag, attack);
    int index = channel_index(channel);
    if (index < 0 || !m4_hit(hit)) return modified;
    float defense = lane[LANE_DEFENSE + index];
    return defense > 0.0f ? modified * m4_armour_factor(damage_distance(hit)) : modified;
}

static int vtable_write(void **slot, void *value) {
    DWORD old;
    if (!VirtualProtect(slot, sizeof(*slot), PAGE_READWRITE, &old)) return 0;
    InterlockedExchangePointer(slot, value);
    VirtualProtect(slot, sizeof(*slot), old, &old);
    return 1;
}

void *m4_string_cvar(void *console, const char *name, const char *start, const char *help) {
    void **table = *(void ***)console;
    void *(*register_string)(void *, const char *, const char *, int, const char *, void *) = table[CONSOLE_REGISTER_STRING / 8];
    void *cvar = register_string(console, name, start, 0, help, NULL);
    char line[128];
    if (cvar && *(unsigned char **)cvar == damage_game + STRING_CVAR_VTABLE_RVA) {
        snprintf(line, sizeof(line), "console: variable %s created as \"%s\"", name, start);
        note(line);
        return cvar;
    }
    snprintf(line, sizeof(line), "console: %s could not be created", name);
    note(line);
    return NULL;
}

